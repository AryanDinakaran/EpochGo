        llm_output = await self._query_llm(prompt)
        if llm_output and len(llm_output.strip()) > 150:
            return llm_output.strip()

        # Deterministic high-quality markdown template fallback
        missing_rows = ""
        for col, info in raw_profile["missing_values"].items():
            missing_rows += f"| `{col}` | {info['count']} ({info['percentage']}%) | 0 (0.0%) | Median/Mode Imputation |\n"
        if not missing_rows:
            missing_rows = "| None | 0 (0.0%) | 0 (0.0%) | No missing values detected |\n"

